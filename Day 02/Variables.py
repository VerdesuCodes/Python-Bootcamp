# [] In a string is used to access a character at a specific index. The index starts at 0 for the first character, 1 for the second character, and so on.

print("Hello"[0]) # This will print the first character of the string "Hello", which is 'H'.

print("Hello"[-2]) # Negative indexing starts from the end of the string, with -1 being the last character, -2 being the second to last character, and so on.

print(123_456_789) # Underscores can be used in numeric literals for better readability. This will print the number 123456789.
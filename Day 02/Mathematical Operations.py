print(6 // 2) # This will print the result of integer division of 6 by 2, which is 3.

print(3 ** 3) # This will print the result of 2 raised to the power of 3, which is 8.

print(3 * (3 + 3) / 3 - 3) 

round(8 / 3, 2) # This will print the result of dividing 8 by 3 and rounding it to 2 decimal places, which is 2.67.

print(f"You score is {round(8 / 3, 2)}") # Used to put variable in a string. This will print "Your score is 2.67".